#!/usr/bin/env python3
"""
code_changes.py
---------------
Writes phase3/documentation/PHASE3_CODE_DIFFS.md, the exact record behind
PHASE3_CODE_CHANGES.md:

  Part 1  every pre-existing file Phase 3 modified: its diff against commit 857d932
          (the clean data baseline committed before any Phase 3 change), from git
  Part 2  every file Phase 3 created, with its size
  Part 3  every new Phase 3 code file as first generated (vibe_coding snapshots,
          before it was run) against its current version

    python phase3/tools/code_changes.py
"""

from __future__ import annotations
import difflib
import os
import subprocess

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(BASE, "phase3", "documentation", "PHASE3_CODE_DIFFS.md")
BASELINE = "857d932"
CODE = (".py", ".sql", ".mjs", ".html", ".yml", ".env", ".example", "Dockerfile.phase3", ".dockerignore", ".gitignore")
SKIP_PREFIX = ("Project2_Asali_Nakali/", "vibe_coding/", "deploy/nodes/", "deploy/coordinator-state/", "data/documents/",
               "phase3/documentation/evidence/", "__pycache__")
MAX_LINES = 400


def git(*args):
    return subprocess.run(["git", *args], cwd=BASE, capture_output=True, text=True, encoding="utf-8").stdout


def is_code(path):
    return path.endswith(CODE) or os.path.basename(path) in ("Dockerfile.phase3",)


def main():
    modified = [l[3:] for l in git("status", "--porcelain").splitlines() if l.startswith(" M") or l.startswith("M ")]
    untracked = [l[3:] for l in git("status", "--porcelain", "--untracked-files=all").splitlines() if l.startswith("??")]
    created = [p for p in untracked if not p.startswith(SKIP_PREFIX) and "__pycache__" not in p]
    L = ["# Phase 3 code diffs (generated)", "",
         f"*Generated by `phase3/tools/code_changes.py` from git and the vibe-coding snapshots. Baseline: commit "
         f"`{BASELINE}` (clean data, before any Phase 3 change). Diffs longer than {MAX_LINES} lines are cut; "
         f"run `git diff {BASELINE} -- <file>` for the whole.*", "",
         "## Part 1 - pre-existing files modified", "",
         "| File | Lines added | Lines removed |", "|---|---|---|"]
    stats = {}
    for line in git("diff", "--numstat", BASELINE, "--", *modified).splitlines():
        a, r, f = line.split("\t")
        stats[f] = (a, r)
    for f in modified:
        a, r = stats.get(f, ("-", "-"))
        L.append(f"| `{f}` | {a} | {r} |")
    L.append("")
    for f in modified:
        if not is_code(f):
            continue
        d = git("diff", BASELINE, "--", f).splitlines()
        L += [f"### `{f}`", "", "```diff"] + d[:MAX_LINES] + (["... (cut)"] if len(d) > MAX_LINES else []) + ["```", ""]
    L += ["## Part 2 - files created by Phase 3", "", "| File | Lines |", "|---|---|"]
    for f in sorted(created):
        try:
            n = sum(1 for _ in open(os.path.join(BASE, f), encoding="utf-8", errors="replace"))
        except OSError:
            n = "-"
        L.append(f"| `{f}` | {n} |")
    L += ["", "The generated corpus (`data/documents/`, 303 files + ground truth) and the evidence files are not listed one by one.", "",
          "## Part 3 - new code as first generated vs now", "",
          "Snapshots: `vibe_coding/generated_v0_phase3/` (P3-1, P3-2), `vibe_coding/rounds/17-score-context/generated/` (P3-3), "
          "`vibe_coding/rounds/18-document-retrieval/generated/` (P3-4). For each file the latest snapshot is compared with the "
          "current file; every difference is explained in `vibe_coding/CHANGES_PHASE3.md`.", ""]
    snaps = [os.path.join(BASE, "vibe_coding", "generated_v0_phase3"),
             os.path.join(BASE, "vibe_coding", "rounds", "17-score-context", "generated"),
             os.path.join(BASE, "vibe_coding", "rounds", "18-document-retrieval", "generated")]
    latest = {}
    for s in snaps:
        for root, _d, files in os.walk(s):
            for fn in files:
                if fn == "SNAPSHOT_TAKEN_AT.txt":
                    continue
                rel = os.path.relpath(os.path.join(root, fn), s).replace("\\", "/")
                latest[rel] = os.path.join(root, fn)
    unchanged = []
    for rel in sorted(latest):
        cur = os.path.join(BASE, rel)
        if not os.path.exists(cur) or not is_code(rel):
            continue
        a = open(latest[rel], encoding="utf-8", errors="replace").read().splitlines()
        b = open(cur, encoding="utf-8", errors="replace").read().splitlines()
        d = list(difflib.unified_diff(a, b, f"generated/{rel}", f"current/{rel}", lineterm="", n=2))
        if not d:
            unchanged.append(rel)
            continue
        L += [f"### `{rel}`", "", "```diff"] + d[:MAX_LINES] + (["... (cut)"] if len(d) > MAX_LINES else []) + ["```", ""]
    L += ["Unchanged since generated: " + ", ".join(f"`{u}`" for u in unchanged), ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"{len(modified)} modified, {len(created)} created, {len(latest)} snapshotted -> {OUT}")


if __name__ == "__main__":
    main()
