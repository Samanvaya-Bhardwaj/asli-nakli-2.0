"""Phase 2 for the regulator: every issued code that approximately matches a noisy reading, and the reverse.

Forward: a reading that is not (or not clearly) an issued code. Candidates are generated by the weighted edit
search with the check character (`asali_codes.candidates`), kept only if a maker has issued them, and listed
cheapest first with the record each one points at and whether the lot printed beside the code fits it.

Reverse: an issued code. Every reading the consumer portals recorded against it that was not the exact code is
listed with how far it was and which edits explain it, so a pattern of slips (the same two characters confused
again and again) is visible.

Nothing here corrects anything. A person decides.
"""

import asyncio
from datetime import date
from typing import Any

from asali_codes.candidates import serial_candidates
from asali_codes.confusion import weighted_distance
from asali_codes.parse import parse

from asali_node.network.client import SourceUnavailable
from asali_node.verify.checks import _existing

MAX_COST, LIMIT, MAX_READINGS = 3.0, 30, 100


async def _scans(share: Any, org: str, gtin: str, serial: str) -> list[dict[str, Any]]:
    try:
        return list((await share.get(org, f"/share/v1/scans/{gtin}/{serial}/inputs"))["inputs"])
    except SourceUnavailable:
        return []


async def _views(share: Any, orgs: list[dict[str, Any]], serials: list[str]) -> dict[str, dict[str, Any]]:
    """What each maker holds for each candidate: its product number, lot and expiry."""

    async def one(s: str) -> tuple[str, dict[str, Any] | None]:
        org = _maker(orgs, s)
        if org is None:
            return s, None
        try:
            return s, dict(await share.get(org, f"/share/v1/units/by-serial/{s}"))
        except SourceUnavailable:
            return s, None

    return {s: v for s, v in await asyncio.gather(*[one(s) for s in serials[:LIMIT]]) if v is not None}


def _maker(orgs: list[dict[str, Any]], serial: str) -> str | None:
    return next((o["org_id"] for o in orgs if o.get("issuer_code") == serial[:2]), None)


async def find_similar(share: Any, orgs: list[dict[str, Any]], raw: str) -> dict[str, Any]:
    issuers = {o["issuer_code"] for o in orgs if o.get("issuer_code")}
    p = parse(raw)
    out: dict[str, Any] = {
        "read": {
            "raw": raw,
            "serial": p.serial,
            "lot": p.lot,
            "expiry": p.expiry.isoformat() if p.expiry else None,
        },
        "matches": [],
        "seen_as": [],
    }
    if not p.serial:
        return out
    gtin = p.gtin if p.status["gtin"] == "valid" else None
    cands = serial_candidates(p.serial, issuers, max_cost=MAX_COST, limit=LIMIT)
    real = await _existing(share, orgs, gtin, [c.value for c in cands])
    cands = [c for c in cands if c.value in real]
    views = await _views(share, orgs, [c.value for c in cands])
    brands: dict[str, dict[str, str]] = {}
    for org in {_maker(orgs, c.value) for c in cands} - {None}:
        try:
            for x in (await share.get(str(org), "/share/v1/products"))["products"]:
                brands[x["gtin"]] = x
        except SourceUnavailable:
            continue
    for c in cands:
        v = views.get(c.value, {})
        lot = v.get("lot")
        expiry = date.fromisoformat(str(v["expiry"])[:10]) if v.get("expiry") else None
        g = gtin or v.get("gtin")
        brand = brands.get(g or "", {})
        fits = None
        if p.lot and lot:
            fits = lot == p.lot
        if p.expiry and expiry and fits is not False:
            fits = expiry == p.expiry
        out["matches"].append(
            {
                "serial": c.value,
                "gtin": g,
                "org_id": _maker(orgs, c.value),
                "cost": c.cost,
                "edits": list(c.edits),
                "lot": lot,
                "expiry": expiry.isoformat() if expiry else None,
                "product": f"{brand.get('brand', '')} {brand.get('strength', '')}".strip() or None,
                "fits_label": fits,
            }
        )
    exact = next((m for m in out["matches"] if m["cost"] == 0), None)
    if exact and exact["gtin"]:
        consumers = [o["org_id"] for o in orgs if o["org_type"] == "consumer"]
        found = await asyncio.gather(*[_scans(share, c, exact["gtin"], exact["serial"]) for c in consumers])
        for consumer, rows in zip(consumers, found, strict=True):
            for r in rows[:MAX_READINGS]:
                seen = parse(r["raw_input"]).serial or r["raw_input"]
                if seen == exact["serial"]:
                    continue
                edits = next(
                    (c.edits for c in serial_candidates(seen, issuers) if c.value == exact["serial"]), ()
                )
                out["seen_as"].append(
                    {
                        "raw_input": r["raw_input"],
                        "serial_read": seen,
                        "cost": weighted_distance(exact["serial"], seen),
                        "edits": list(edits),
                        "city": r["city"],
                        "at": r["at"],
                        "portal": consumer,
                    }
                )
        out["seen_as"].sort(key=lambda s: (s["cost"], s["at"]))
    return out
