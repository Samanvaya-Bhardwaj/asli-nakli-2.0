-- Kesar Biologics: SQLite, legacy ERP style. UPPER_CASE names, text dates in Indian format, one-letter codes.
CREATE TABLE IF NOT EXISTS ITEM_MST (
  ITEM_CD TEXT PRIMARY KEY, GTIN TEXT UNIQUE NOT NULL, ITEM_DESC TEXT NOT NULL, MOL_DESC TEXT NOT NULL,
  STR TEXT NOT NULL, UOM TEXT NOT NULL, STOR_TEMP_TXT TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS LOT_MST (
  LOT_NO TEXT PRIMARY KEY, ITEM_CD TEXT NOT NULL REFERENCES ITEM_MST(ITEM_CD),
  MFG_DT TEXT NOT NULL, EXP_DT TEXT NOT NULL, LOT_STAT TEXT NOT NULL CHECK (LOT_STAT IN ('A','Q','R')));
CREATE TABLE IF NOT EXISTS SRL_MST (
  SRL_NO TEXT PRIMARY KEY, LOT_NO TEXT NOT NULL REFERENCES LOT_MST(LOT_NO),
  SRL_STAT TEXT NOT NULL CHECK (SRL_STAT IN ('C','D','X')), CRT_TS TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS PARTY_MST (
  PARTY_CD TEXT PRIMARY KEY, PARTY_NM TEXT NOT NULL, NET_ORG_ID TEXT);
CREATE TABLE IF NOT EXISTS DSP_HDR (
  DSP_NO TEXT PRIMARY KEY, PARTY_CD TEXT NOT NULL REFERENCES PARTY_MST(PARTY_CD),
  DSP_DT TEXT NOT NULL, TRUCK_NO TEXT);
CREATE TABLE IF NOT EXISTS DSP_DTL (
  DSP_NO TEXT NOT NULL REFERENCES DSP_HDR(DSP_NO), SRL_NO TEXT NOT NULL REFERENCES SRL_MST(SRL_NO),
  PRIMARY KEY (DSP_NO, SRL_NO));
CREATE TABLE IF NOT EXISTS RCL_REG (
  RCL_NO TEXT PRIMARY KEY, LOT_NO TEXT NOT NULL REFERENCES LOT_MST(LOT_NO), RCL_RSN TEXT NOT NULL, RCL_DT TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS USR_MST (
  USR_ID TEXT PRIMARY KEY, PWD_HASH TEXT NOT NULL, USR_ROLE TEXT NOT NULL, USR_NM TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS SCN_CORR (
  CORR_ID INTEGER PRIMARY KEY, CORR_TS TEXT NOT NULL, RAW_TXT TEXT NOT NULL, FLD TEXT NOT NULL,
  CHOSEN_VAL TEXT NOT NULL, COST REAL NOT NULL, CONF_BY TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS DOC_LNK (
  DOC_ID TEXT NOT NULL, ENT_TYPE TEXT NOT NULL, ENT_KEY TEXT NOT NULL, CONF REAL NOT NULL, LNK_TS TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS IX_SRL_LOT ON SRL_MST(LOT_NO);
CREATE INDEX IF NOT EXISTS IX_DOCLNK_KEY ON DOC_LNK(ENT_KEY)
